// Embeds the library/ text files into a TypeScript module so the function bundle
// carries them without relying on runtime file paths. Runs as the Netlify build command.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const libraryDir = join(root, "library");
const out = join(root, "netlify", "lib", "library-data.ts");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const files = {};
for (const path of walk(libraryDir).filter((p) => p.endsWith(".txt")).sort()) {
  const key = relative(libraryDir, path).split(sep).join("/");
  files[key] = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
}

writeFileSync(
  out,
  "// Generated by netlify/embed-library.mjs from library/. Do not edit.\n" +
    `export const LIBRARY: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`,
);
console.log(`Embedded ${Object.keys(files).length} library files into ${relative(root, out)}`);
